def build_holdout():
    """Return 32 answerable rows and 8 separately scored no-match rows.

    ``pos == []`` identifies a rejection case.  Families, not individual query
    variants, are the independent units; never split the variants across sets.
    Every call returns fresh mutable row and candidate objects.
    """
    rows = []
    for family in _FAMILIES + _NO_MATCH_FAMILIES:
        for index, query in enumerate(family["queries"]):
            variant = "base" if index == 0 else "paraphrase"
            rows.append(
                {
                    "id": f"{family['family']}_{variant}",
                    "group": family["group"],
                    "family": family["family"],
                    "query": query,
                    "pos": deepcopy(family["pos"]),
                    "neg": deepcopy(family["neg"]),
                    "rationale": family["rationale"],
                    "variant": variant,
                }
            )
    return rows
