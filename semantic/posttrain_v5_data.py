def build_dataset(parent_data):
    """Caller must supply the verified V4 training snapshot, not evaluation data."""
    if len(parent_data.get("train", [])) != 144 or parent_data.get("dev") != []:
        raise ValueError("Exactly the completed V4 144-row training snapshot is required")
    train = copy.deepcopy(parent_data["train"])
    for family, topic, audience, queries, positive, negatives, rationale in NEW:
        for variant, query in enumerate(queries, 1):
            train.append(dict(id=f"v5_{family}_{variant}", family="v5_"+family, group="v5_new",
                query=query, pos=[positive], neg=list(negatives), factual_passages=[positive]+list(negatives),
                origin="v5_new_synthetic_family", variant=f"wording_{variant}", topic=topic,
                audience=audience, rationale=rationale))
    return dict(train=train, dev=[], notice="192 synthetic training phrasings in 48 fact families: exact 144 V4 rows plus 48 new phrasings in 12 families. No evaluation rows, private resumes or model-generated labels; retrieval experiment only.")


def content_hash(value):
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def validate(parent_data):
    data=build_dataset(parent_data);rows=data["train"]
    assert rows[:144] == parent_data["train"]
    assert len(rows)==192 and len({r["family"] for r in rows})==48
    assert len({r["id"] for r in rows})==len({r["query"] for r in rows})==192
    assert len(NEW)==12 and not {r["family"] for r in rows[:144]} & {r["family"] for r in rows[144:]}
    for row in rows:
        assert len(row["pos"])==1 and len(row["neg"])==3 and len(set(row["pos"]+row["neg"]))==4
    for row in rows[144:]:
        assert row["factual_passages"]==row["pos"]+row["neg"]
        assert len(row["rationale"])>20 and 4==sum(r["family"]==row["family"] for r in rows[144:])
    return dict(training_phrasings=192, independent_families=48, retained_verbatim=144,
                new_phrasings=48,new_families=12,dev_rows=0,real_resumes=0,evaluation_rows=0,
                retained_rows_hash=content_hash(rows[:144]),new_rows_hash=content_hash(rows[144:]),dataset_hash=content_hash(data))
