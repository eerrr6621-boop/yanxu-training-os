def _normalise(text: str) -> str:
    return re.sub(r"[\W_]+", "", unicodedata.normalize("NFKC", text)).casefold()


def validate_dataset() -> dict:
    """Read only the in-memory authored records; fail on accidental drift."""
    assert len(TRAIN_DATA) == 80, "Training count must stay frozen at 80."
    assert len(DEV_DATA) == 16, "Development count must stay frozen at 16."
    assert set(row["group"] for row in TRAIN_DATA) == _TRAIN_GROUPS
    assert set(row["group"] for row in DEV_DATA) == _DEV_GROUPS
    assert _TRAIN_GROUPS.isdisjoint(_DEV_GROUPS)
    all_rows = TRAIN_DATA + DEV_DATA
    assert len({row["id"] for row in all_rows}) == len(all_rows)
    queries: set[str] = set()
    passages: set[str] = set()
    for row in all_rows:
        assert row["label_source"] == "synthetic_author" and row["synthetic"] is True
        query = _normalise(row["query"])
        assert query and query not in queries, f"Duplicate query: {row['id']}"
        queries.add(query)
        assert 1 <= len(row["pos"]) <= 2
        assert 3 <= len(row["neg"]) <= 5
        assert len(row["rationale"]["positive"]) == len(row["pos"])
        assert len(row["rationale"]["negative"]) == len(row["neg"])
        for passage in row["pos"] + row["neg"]:
            assert isinstance(passage, str) and len(passage) >= 30
            assert "\n" not in passage and passage.endswith("。")
            canonical = _normalise(passage)
            assert canonical not in passages, f"Duplicate passage: {row['id']}"
            passages.add(canonical)
    for split in (TRAIN_DATA, DEV_DATA):
        counts = Counter(row["group"] for row in split)
        assert all(count == 8 for count in counts.values())
        for group in counts:
            facets = {row["facet"] for row in split if row["group"] == group}
            assert facets == set(_POSITIVE_REASONS), f"Missing evidence boundary: {group}"
    return {
        "train": len(TRAIN_DATA),
        "dev": len(DEV_DATA),
        "train_groups": dict(Counter(row["group"] for row in TRAIN_DATA)),
        "dev_groups": dict(Counter(row["group"] for row in DEV_DATA)),
        "unique_queries": len(queries),
        "unique_passages": len(passages),
        "positive_passages": sum(len(row["pos"]) for row in all_rows),
        "negative_passages": sum(len(row["neg"]) for row in all_rows),
        "model_input_fields": DATASET_METADATA["model_input_fields"],
        "notice": NOTICE,
    }


def build_dataset() -> dict:
    """Return detached fixed arrays, preserving audit metadata outside inputs."""
    validate_dataset()
    return json.loads(json.dumps({
        "train": TRAIN_DATA,
        "dev": DEV_DATA,
        "notice": NOTICE,
        "metadata": DATASET_METADATA,
    }, ensure_ascii=False))


