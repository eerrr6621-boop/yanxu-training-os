def _row(facet: str, query: str, positive: str, *negatives: tuple[str, str]) -> dict:
    """Keep prose separate from author explanations; no text augmentation."""
    return {
        "facet": facet,
        "query": query,
        "pos": [positive],
        "neg": [passage for _, passage in negatives],
        "rationale": {
            "positive": [_POSITIVE_REASONS[facet]],
            "negative": [reason for reason, _ in negatives],
        },
        "label_source": "synthetic_author",
        "synthetic": True,
    }


def _group(split: str, slug: str, topic: str, rows: list[dict]) -> list[dict]:
    return [
        {"id": f"{split}-{slug}-{index:02d}", "group": topic, **record}
        for index, record in enumerate(rows, start=1)
    ]


