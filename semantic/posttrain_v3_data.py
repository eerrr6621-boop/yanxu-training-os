def length_variant(text, target, salt):
    # Every label receives neutral formatting facts. Each candidate visits all
    # four length ranks across its family's four query variants, avoiding the
    # original "positive is always longest" shortcut without changing claims.
    result=text+"\n文档编排附录\n"
    i=salt % len(ADMIN_NOTES)
    while len(result)<target:
        result+=ADMIN_NOTES[i % len(ADMIN_NOTES)]; i+=1
    return result


def rows(cases, split):
    result=[]
    for family,group,queries,positive,negative,rationale in cases:
        for i,query in enumerate(queries):
            texts=[positive]+list(negative)
            if split=="train":
                salt=int(hashlib.sha256(family.encode()).hexdigest()[:8],16)
                baseline=max(map(len,texts))+24
                texts=[length_variant(t,baseline+32*((j+i+salt)%4),salt+j+i)
                       for j,t in enumerate(texts)]
            result.append(dict(id=f"v3_{family}_{i+1}",group=group,family=family,
                query=query,pos=texts[:1],neg=texts[1:],rationale=rationale,variant=f"wording_{i+1}",
                factual_passages=[positive]+list(negative)))
    return result


def build_dataset():
    return dict(train=rows(TRAIN,"train"),dev=rows(DEV,"dev"),notice=
        "Hand-authored synthetic facts; no real resumes, prior evaluation cases or model labels. "
        "Same family paraphrases stay together. Dev authored separately but not a business blind set. "
        "Training adds neutral formatting appendices, rotating every candidate through four length ranks. "
        "Dev has no appendices. Shared family facts are intentional, never independent evidence.")


def validate():
    d=build_dataset();train,dev=d["train"],d["dev"]
    assert len(train)==96 and len(dev)==16
    assert not {r["family"] for r in train}&{r["family"] for r in dev}
    assert not {r["group"] for r in train}&{r["group"] for r in dev}
    assert len({r["query"] for r in train+dev})==len(train+dev)
    for r in train+dev:
        assert len(r["pos"])==1 and len(r["neg"])==3 and len(set(r["pos"]+r["neg"]))==4
        assert r["rationale"]
    texts=lambda rs:{t for r in rs for t in [r["query"]]+r["pos"]+r["neg"]}
    assert not texts(train)&texts(dev)
    return {"train":len(train),"dev":len(dev),"train_families":24,"dev_families":8}


