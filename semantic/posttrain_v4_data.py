def build_dataset():
    previous = previous_dataset()
    # Reuse training only. Earlier dev and all evaluation sets remain excluded.
    train = [dict(row, id="v4_retained_" + row["id"], origin="v3_training_retention")
             for row in previous["train"]]
    for family, queries, positive, negatives in NEW:
        salt = int(hashlib.sha256(family.encode()).hexdigest()[:8], 16)
        facts = [positive] + negatives
        baseline = max(map(len, facts)) + 24
        for i, query in enumerate(queries):
            texts = [length_variant(text, baseline + 32 * ((j + i + salt) % 4), salt + i + j)
                     for j, text in enumerate(facts)]
            train.append(dict(id=f"v4_{family}_{i+1}", family=family, group="v4_new",
                query=query, pos=texts[:1], neg=texts[1:], factual_passages=facts,
                origin="new_synthetic_family", variant=f"wording_{i+1}",
                rationale="正例明确本人已教授所需内容；负例分别缺少已授事实、本人归属或完整主题，不能当作已满足。"))
    return dict(train=train, dev=[], notice=
        "144 synthetic training phrasings in 36 fact families: 96 retained V3 training rows and 48 new phrasings. "
        "No real resumes, prior dev/evaluation rows or held-out labels. Model learns retrieval, not factual certification.")


def validate():
    rows = build_dataset()["train"]
    assert len(rows) == 144 and len({r["family"] for r in rows}) == 36
    assert len({r["id"] for r in rows}) == len({r["query"] for r in rows}) == 144
    assert len(NEW) == 12
    for row in rows:
        assert len(row["pos"]) == 1 and len(row["neg"]) == 3
        assert len(set(row["pos"] + row["neg"])) == 4
        assert len(row["factual_passages"]) == 4
        assert all(fact in rendered for fact, rendered in zip(row["factual_passages"], row["pos"] + row["neg"]))
    assert not {r["family"] for r in rows} & {r["family"] for r in previous_dataset()["dev"]}
    return dict(training_phrasings=144, independent_families=36, new_phrasings=48,
                new_families=12, actual_resumes=0, evaluation_rows=0)


if __name__ == "__main__":
    print(validate())
